#!/usr/bin/env bash
# ============================================================
# 将系统语言切换为简体中文（zh_CN.UTF-8）
#
# 用法: setup-locale-zh.sh
#
# 说明:
#   - 生成 zh_CN.UTF-8，写入 /etc/locale.conf（/etc/default/locale 符号链接）
#   - 当前 shell 不会立即改变，需重新登录 / 重启图形会话
#   - 安装 fonts-noto-cjk 中文字体
# ============================================================
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=_common.sh
source "$SCRIPT_DIR/_common.sh"

TARGET_LANG="${PENTEST_LANG:-zh_CN.UTF-8}"
TARGET_LANGUAGE="${PENTEST_LANGUAGE:-zh_CN:zh}"
while (($#)); do
    case "$1" in
        -h|--help) sed -n '2,11p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) log_err "未知参数: $1"; exit 2 ;;
    esac
done

require_root

LOCALE_GEN="/etc/locale.gen"
LOCALE_CONF="/etc/locale.conf"

# ---------- locales 包 ----------
if ! command -v locale-gen >/dev/null 2>&1; then
    log_info "安装 locales 包..."
    apt-get update -qq
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq locales
fi

# ---------- 启用 zh_CN.UTF-8 ----------
if grep -qE '^#[[:space:]]*zh_CN\.UTF-8[[:space:]]+UTF-8' "$LOCALE_GEN"; then
    sed -i -E 's/^#[[:space:]]*(zh_CN\.UTF-8[[:space:]]+UTF-8)/\1/' "$LOCALE_GEN"
fi
if ! grep -qE '^zh_CN\.UTF-8[[:space:]]+UTF-8' "$LOCALE_GEN"; then
    printf 'zh_CN.UTF-8 UTF-8\n' >> "$LOCALE_GEN"
fi

log_info "生成 zh_CN.UTF-8 locale..."
if ! locale-gen zh_CN.UTF-8 >/dev/null; then
    log_err "locale-gen 执行失败，请检查 $LOCALE_GEN"
    exit 1
fi

if ! locale -a 2>/dev/null | grep -qiE '^zh_CN\.utf-?8$'; then
    log_err "locale 生成失败，请检查 $LOCALE_GEN"
    exit 1
fi

# ---------- 写入系统默认 locale ----------
[[ -f "$LOCALE_CONF.pentest.bak" ]] || cp -a "$LOCALE_CONF" "$LOCALE_CONF.pentest.bak" 2>/dev/null || true
LC_ALL=C update-locale LANG="$TARGET_LANG" LANGUAGE="$TARGET_LANGUAGE"

if ! grep -Fqx "LANG=$TARGET_LANG" "$LOCALE_CONF" 2>/dev/null; then
    log_warn "update-locale 未写入预期值，直接写入 $LOCALE_CONF"
    {
        echo "# File generated by kali-setup"
        echo "LANG=$TARGET_LANG"
        echo "LANGUAGE=$TARGET_LANGUAGE"
    } > "$LOCALE_CONF"
fi

if command -v localectl >/dev/null 2>&1 && [[ -d /run/systemd/system ]] \
   && ! grep -Fqx "LANG=$TARGET_LANG" "$LOCALE_CONF"; then
    localectl set-locale LANG="$TARGET_LANG" LANGUAGE="$TARGET_LANGUAGE" >/dev/null 2>&1 \
        || log_warn "localectl set-locale 失败（update-locale 已写入，可忽略）"
fi

current_lang="$(sed -n 's/^LANG=//p' "$LOCALE_CONF" | tail -n1)"
[[ "$current_lang" == "$TARGET_LANG" ]] \
    || { log_err "系统 locale 写入失败（当前: ${current_lang:-空}）"; exit 1; }

# ---------- 中文字体 ----------
if dpkg-query -W -f='${Status}' fonts-noto-cjk 2>/dev/null | grep -q 'install ok installed'; then
    log_info "中文字体 fonts-noto-cjk 已安装"
else
    log_info "安装中文字体 fonts-noto-cjk..."
    if ! DEBIAN_FRONTEND=noninteractive apt-get install -y -qq fonts-noto-cjk; then
        apt-get update -qq || true
        DEBIAN_FRONTEND=noninteractive apt-get install -y -qq fonts-noto-cjk \
            || log_warn "fonts-noto-cjk 安装失败，中文界面可能显示方框"
    fi
fi

log_info "系统语言已设为 $TARGET_LANG"
log_warn "当前 shell 不会立即改变：请重新登录，或开新终端"
log_info "临时生效: export LANG=$TARGET_LANG LANGUAGE=$TARGET_LANGUAGE; unset LC_ALL"
